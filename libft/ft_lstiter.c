#include "libft.h"

void	ft_lstiter(t_list *lst, void (*f)(void *))
{
	t_list	*tmp;

	tmp = lst;
	while (tmp)
	{
		f(tmp->content);
		if (tmp->next != (void *)0)
			tmp = tmp->next;
		else
			break ;
	}
}
